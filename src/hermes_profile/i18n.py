def language() -> str:
    return _current


def set_language(value: str) -> str:
    global _current
    if value not in LANGUAGE_NAMES:
        value = DEFAULT_LANGUAGE
    _current = value
    return _current


def next_language(current: str | None = None) -> str:
    now = current or _current
    try:
        index = LANGUAGES.index(now)
    except ValueError:
        return LANGUAGES[0]
    return LANGUAGES[(index + 1) % len(LANGUAGES)]


def t(key: str, **kwargs: object) -> str:
    table = STRINGS.get(_current) or STRINGS[DEFAULT_LANGUAGE]
    text = table.get(key) or STRINGS[DEFAULT_LANGUAGE].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
